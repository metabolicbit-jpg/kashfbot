// منوهای زیرشاخه
export function getHelpMenu(cat) {
  const menu = HELP_SUBMENUS[cat];
  if (!menu) return HELP_KB_MAIN;
  const rows = [];
  for (let i = 0; i < menu.items.length; i += 2) {
    rows.push(menu.items.slice(i, i + 2));
  }
  rows.push([{text:"🔙 بازگشت به راهنما", callback_data:"help_menu"}]);
  return { inline_keyboard: rows };
}

